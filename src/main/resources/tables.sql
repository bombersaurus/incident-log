CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('staff', 'supervisor'))
);

CREATE TABLE IF NOT EXISTS incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP NOT NULL,
    location VARCHAR(200) NOT NULL,
    category VARCHAR(50) NOT NULL,
    severity INT NOT NULL,
    description VARCHAR(4000) NOT NULL,
    bodycam_ref VARCHAR(50) NOT NULL,
    reported_by BIGINT NOT NULL REFERENCES users (id),
    created_at TIMESTAMP NOT NULL
);

-- One row for every field somebody changed on an incident.
CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents (id),
    user_id BIGINT NOT NULL REFERENCES users (id),
    field VARCHAR(50) NOT NULL,
    old_value VARCHAR(4000) NOT NULL,
    new_value VARCHAR(4000) NOT NULL,
    changed_at TIMESTAMP NOT NULL
);
